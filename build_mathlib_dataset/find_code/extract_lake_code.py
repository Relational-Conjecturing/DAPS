def normalize_token(token: str) -> str:
    token = token.strip()
    if token.endswith(":"):
        token = token[:-1]
    return token


def strip_leading_attributes(text: str) -> str:
    stripped = text.lstrip()
    while stripped.startswith("@["):
        depth = 0
        idx = 0
        while idx < len(stripped):
            ch = stripped[idx]
            if ch == "[":
                depth += 1
            elif ch == "]":
                depth -= 1
                if depth <= 0:
                    idx += 1
                    break
            idx += 1
        if depth > 0:
            break
        stripped = stripped[idx:].lstrip()
    return stripped


def guess_keyword(line: str) -> Tuple[str, List[str]]:
    stripped = strip_leading_attributes(line).strip()
    tokens = stripped.split()
    qualifiers: List[str] = []
    idx = 0
    while idx < len(tokens):
        tok = normalize_token(tokens[idx])
        if tok in QUALIFIER_TOKENS:
            qualifiers.append(tok)
            idx += 1
            continue
        # handle combinations like "private unsafe def"
        if tok in {"unsafe"}:
            qualifiers.append(tok)
            idx += 1
            continue
        break
    keyword = normalize_token(tokens[idx]) if idx < len(tokens) else ""
    if keyword and (
        keyword not in COMMAND_START_KEYWORDS
        and keyword not in KEYWORD_MAP
        and keyword not in KIND_FALLBACK_MAP
    ):
        keyword = ""
    return keyword, qualifiers


def find_parent_keyword(
    lines: Sequence[str],
    decl_idx: int,
) -> Tuple[Optional[str], List[str]]:
    k = decl_idx - 1
    block_balance = 0
    qualifiers: List[str] = []
    while k >= 0:
        line = lines[k]
        stripped = line.strip()
        if not stripped:
            k -= 1
            continue
        if stripped.startswith("--"):
            k -= 1
            continue
        open_count = stripped.count("/-")
        close_count = stripped.count("-/")
        block_balance += close_count - open_count
        if block_balance > 0:
            k -= 1
            continue
        if stripped.startswith("/-") or stripped.startswith("-/"):
            k -= 1
            continue
        keyword, line_qualifiers = guess_keyword(stripped)
        if keyword:
            return keyword, line_qualifiers
        if stripped.endswith("where"):
            first = stripped.split(maxsplit=1)[0]
            normalized = normalize_token(first) if first else ""
            if normalized and (
                normalized in COMMAND_START_KEYWORDS
                or normalized in KEYWORD_MAP
                or normalized in KIND_FALLBACK_MAP
            ):
                return normalized, []
        k -= 1
    return None, []


def find_enclosing_structure_line(
    lines: Sequence[str],
    decl_idx: int,
) -> Optional[Tuple[int, int]]:
    """Locate the snippet bounds (start, decl_idx) of the enclosing structure/class block."""
    decl_indent = indent_of(lines[decl_idx])
    if decl_indent == 0:
        return None
    block_balance = 0
    k = decl_idx - 1
    while k >= 0:
        line = lines[k]
        stripped = line.strip()
        if not stripped:
            k -= 1
            continue
        if stripped.startswith("--"):
            k -= 1
            continue
        open_count = stripped.count("/-")
        close_count = stripped.count("-/")
        block_balance += close_count - open_count
        if block_balance > 0:
            k -= 1
            continue
        if stripped.startswith("/-") or stripped.startswith("-/"):
            k -= 1
            continue
        if indent_of(line) < decl_indent:
            keyword, _ = guess_keyword(stripped)
            if keyword in STRUCTURE_LIKE_KEYWORDS:
                parent_decl_idx = k
                parent_start_idx = find_snippet_start(lines, k)
                return parent_start_idx, parent_decl_idx
        k -= 1
    return None


def build_subcategory(
    snippet: Snippet,
    lines: Sequence[str],
    category: Optional[str] = None,
) -> str:
    decl_line = lines[snippet.decl_idx]
    keyword, qualifiers = guess_keyword(decl_line)
    base = KEYWORD_MAP.get(keyword, "")
    if base == "definition" and "partial" in qualifiers:
        base = "partial_definition"
    if base == "definition" and "unsafe" in qualifiers:
        base = "unsafe_definition"
    if qualifiers:
        for q in qualifiers:
            if q in {"private", "protected", "local", "scoped"} and base == "definition":
                base = f"{q}_definition"
                break
    if not base:
        parent_keyword, _ = find_parent_keyword(lines, snippet.decl_idx)
        if parent_keyword == "class":
            base = "class_field"
        elif parent_keyword == "structure":
            base = "structure_field"
        elif parent_keyword == "inductive":
            base = "inductive_component"
        else:
            stripped_decl = decl_line.strip()
            if stripped_decl.startswith("|"):
                base = "constructor"
            else:
                base = "unknown"
    if (not base or base == "unknown") and category:
        base = KIND_FALLBACK_MAP.get(category, base or "")
    base = base or "unknown"
    return BASE_CANONICAL_MAP.get(base, base)


DERIVED_NAME_SUFFIXES = (
    ".casesOn",
    ".rec",
    ".recOn",
    ".cases",
    ".mk",
    ".noConfusion",
    ".injEq",
)


def local_name(full_name: str) -> str:
    return full_name.split(".")[-1]


def is_derived_constant(
    name: str,
    category: Optional[str],
    code: str,
    *,
    isHumanTheorem: Optional[bool] = None,
    is_nested: bool = False,
    decl_base: Optional[str] = None,
) -> bool:
    local = local_name(name)
    code_contains_name = bool(local and local in code)
    stripped_lines: List[str] = []
    block_depth = 0
    for line in code.splitlines():
        stripped = line.strip()
        open_count = line.count("/-")
        close_count = line.count("-/")
        in_block = block_depth > 0
        if not stripped:
            block_depth += open_count - close_count
            if block_depth < 0:
                block_depth = 0
            continue
        if stripped.startswith("--"):
            block_depth += open_count - close_count
            if block_depth < 0:
                block_depth = 0
            continue
        if in_block or stripped.startswith("/-"):
            block_depth += open_count - close_count
            if block_depth < 0:
                block_depth = 0
            continue
        line_without_attrs = strip_leading_attributes(line).lstrip()
        if not line_without_attrs:
            block_depth += open_count - close_count
            if block_depth < 0:
                block_depth = 0
            continue
        stripped_lines.append(line_without_attrs)
        block_depth += open_count - close_count
        if block_depth < 0:
            block_depth = 0
    first_line = stripped_lines[0] if stripped_lines else ""
    if category in {"constructor", "recursor"}:
        return True
    if any(name.endswith(suffix) for suffix in DERIVED_NAME_SUFFIXES):
        return True
    if any(line.startswith("alias ") for line in stripped_lines):
        return True
    if any(line.startswith("@[") and " alias " in line for line in stripped_lines):
        return True
    if "@[to_additive" in code and not code_contains_name:
        return True
    if is_nested and category in {"theorem", "lemma"} and not isHumanTheorem:
        return True
    if (
        isHumanTheorem
        and category in {"theorem", "lemma"}
        and code_contains_name
        and stripped_lines
        and stripped_lines[0].startswith(category)
    ):
        return False
    if first_line and ":=" not in first_line:
        token = first_line.split(None, 1)[0]
        if token not in COMMAND_START_KEYWORDS and token not in {"structure", "class", "inductive"}:
            return True
    if not code_contains_name and decl_base not in {"instance"}:
        return True
    return False


def trim_leading_comments(
    lines: Sequence[str],
    start_idx: int,
    end_idx: int,
) -> int:
    """Return first index in [start_idx, end_idx] that is not a blank/comment line."""
    idx = start_idx
    block_depth = 0
    while idx <= end_idx:
        line = lines[idx]
        stripped = line.strip()
        if block_depth > 0:
            block_depth += line.count("/-") - line.count("-/")
            if block_depth <= 0:
                block_depth = 0
            idx += 1
            continue
        if stripped.startswith("/-"):
            block_depth = line.count("/-") - line.count("-/")
            if block_depth <= 0:
                block_depth = 0
            idx += 1
            continue
        if stripped.startswith("--"):
            idx += 1
            continue
        if not stripped:
            idx += 1
            continue
        break
    return idx


def split_statement_proof(
    snippet: Snippet,
    lines: Sequence[str],
) -> Tuple[str, Optional[str]]:
    start = trim_leading_comments(lines, snippet.start_idx, snippet.decl_idx)
    relevant_start = min(start, snippet.decl_idx)
    raw_lines = lines[relevant_start : snippet.end_idx + 1]
    statement_lines: List[str] = []
    proof_lines: List[str] = []
    split_done = False
    decl_offset = snippet.decl_idx - relevant_start
    assign_rel_idx, assign_pos = find_top_level_assignment(raw_lines, decl_offset)
    for offset, line in enumerate(raw_lines):
        if offset < decl_offset:
            statement_lines.append(line)
            continue
        if not split_done:
            if assign_rel_idx is not None and offset == assign_rel_idx:
                before = line[:assign_pos].rstrip()
                if before:
                    statement_lines.append(before + "\n")
                split_done = True
                after = line[assign_pos + 2 :]
                if after:
                    proof_lines.append(after)
                continue
            if assign_rel_idx is None:
                pos = line.find(":=")
                if pos != -1:
                    before = line[:pos].rstrip()
                    if before:
                        statement_lines.append(before + "\n")
                    split_done = True
                    after = line[pos + 2 :]
                    if after:
                        proof_lines.append(after)
                    continue
            stripped_line = strip_leading_attributes(line).strip()
            if stripped_line == "where" or stripped_line.endswith(" where"):
                statement_lines.append(line)
                split_done = True
                continue
            statement_lines.append(line)
        else:
            proof_lines.append(line)
    statement = "".join(statement_lines).strip()
    proof = "".join(proof_lines).strip()
    return statement, (proof or None)


def strip_comments(text: str) -> str:
    if not text:
        return text
    cleaned = COMMENT_BLOCK_RE.sub("", text)
    result_lines: List[str] = []
    for line in cleaned.splitlines():
        prefix = line.split("--", 1)[0]
        result_lines.append(prefix.rstrip())
    # remove leading/trailing empty lines introduced by stripping
    while result_lines and not result_lines[0].strip():
        result_lines.pop(0)
    while result_lines and not result_lines[-1].strip():
        result_lines.pop()
    return "\n".join(result_lines)


def process_directory(
    lake_path: Path,
    dry_run: bool = False,
) -> ProcessResult:
    lean_path = select_lean_file(lake_path.parent)
    if lean_path is None:
        return ProcessResult(lake_path, processed=False, reason="missing_lean")
    constants = load_constants(lake_path)
    filtered = [c for c in constants if isinstance(c.get("line"), int) and c["line"] > 0]
    if not filtered:
        return ProcessResult(lake_path, processed=False, reason="no_constants")
    lines = read_lines(lean_path)
    unique_lines: List[int] = []
    seen = set()
    for const in filtered:
        line_no = const["line"]
        if line_no not in seen:
            unique_lines.append(line_no)
            seen.add(line_no)
    unique_lines.sort()
    line_to_next: dict[int, Optional[int]] = {}
    for idx, line_no in enumerate(unique_lines):
        next_line = unique_lines[idx + 1] if idx + 1 < len(unique_lines) else None
        line_to_next[line_no] = next_line
    snippets: dict[int, Snippet] = {}
    for line_no in unique_lines:
        next_line = line_to_next[line_no]
        snippets[line_no] = extract_snippet(lines, line_no, next_line)
    enriched = []
    for const in filtered:
        snippet = snippets[const["line"]]
        entry = dict(const)
        if "type" in entry:
            entry["signature"] = entry.pop("type")
        entry["lean4_start"] = snippet.start_idx + 1
        entry["lean4_end"] = snippet.end_idx + 1
        entry["lean4_code"] = snippet.code
        guess_base = build_subcategory(snippet, lines, const.get("category"))
        if is_derived_constant(
            const.get("name", ""),
            const.get("category"),
            snippet.code,
            isHumanTheorem=const.get("isHumanTheorem"),
            is_nested=indent_of(lines[snippet.decl_idx]) > 0,
            decl_base=guess_base,
        ):
            entry["subcategory"] = f"{guess_base}_derived"
        else:
            entry["subcategory"] = guess_base
        entry["in_blacklist"] = entry.get("in_blacklist", False) or entry.get("name") in SKIP_CONSTANTS
        statement, proof = split_statement_proof(snippet, lines)
        if guess_base in {"structure", "class"}:
            statement = snippet.code
            proof = None
        entry["statement"] = strip_comments(statement)
        should_include_proof = (
            entry.get("isProp")
            or entry.get("category") in {"theorem", "lemma"}
            or guess_base in PROOF_KEYWORDS
        )
        if not should_include_proof:
            if (
                entry.get("category") in {"def", "instance", "opaque"}
                or guess_base in {"definition", "instance", "class", "structure"}
            ):
                should_include_proof = proof is not None
        entry["proof"] = proof if should_include_proof else None
        enriched.append(entry)
    output_path = lake_path.parent / "lake_constants_withcode.json"
    if dry_run:
        LOGGER.info("Dry run: would write %s", output_path)
        return ProcessResult(lake_path, processed=False, constants=len(enriched), reason="dry_run")
    with output_path.open("w", encoding="utf-8") as handle:
        json.dump(enriched, handle, ensure_ascii=False, indent=2)
        handle.write("\n")
    return ProcessResult(lake_path, processed=True, constants=len(enriched))


def walk_lake_constants(root: Path) -> Iterable[Path]:
    yield from root.rglob("lake_constants.json")


def process_entry(args: Tuple[str, bool]) -> ProcessResult:
    path_str, dry_run = args
    lake_path = Path(path_str)
    try:
        return process_directory(lake_path, dry_run=dry_run)
    except Exception as exc:  # noqa: BLE001
        LOGGER.exception("Failed processing %s", lake_path)
        return ProcessResult(lake_path, processed=False, reason=f"error:{exc}")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Attach Lean snippets to lake constants.",
    )
    parser.add_argument(
        "--mathlib-root",
        type=Path,
        default=DEFAULT_RELATIVE_ROOT,
        help="Root directory that contains Mathlib Lean folders "
        "(default: %(default)s)",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Process at most this many lake_constants.json files.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Scan files but do not write any output.",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Enable verbose logging.",
    )
    parser.add_argument(
        "--workers",
        type=int,
        default=None,
        help="Number of parallel workers to use (default: 75%% of available CPUs).",
    )
    return parser


def configure_logging(verbose: bool) -> None:
    logging.basicConfig(
        level=logging.DEBUG if verbose else logging.INFO,
        format="%(message)s",
    )


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()
    configure_logging(args.verbose)
    mathlib_root: Path = args.mathlib_root
    if not mathlib_root.exists():
        parser.error(f"mathlib root {mathlib_root} does not exist")
    if not mathlib_root.is_dir():
        parser.error(f"mathlib root {mathlib_root} is not a directory")
    targets = list(walk_lake_constants(mathlib_root))
    targets.sort()
    if args.limit is not None:
        targets = targets[: args.limit]
    if not targets:
        LOGGER.info("No lake_constants.json files found under %s", mathlib_root)
        return
    cpu_total = os.cpu_count() or 1
    default_workers = max(1, math.floor(cpu_total * 0.75))
    workers = args.workers if args.workers is not None else default_workers
    workers = max(1, workers)
    LOGGER.info("Processing %d files with %d worker(s)%s", len(targets), workers, " (dry-run)" if args.dry_run else "")
    results: List[ProcessResult] = []
    if workers == 1:
        for path in targets:
            result = process_directory(path, dry_run=args.dry_run)
            results.append(result)
            # if result.processed:
                # LOGGER.info("Wrote %s (%d constants)", path.parent / "lake_constants_withcode.json", result.constants)
    else:
        with ThreadPoolExecutor(max_workers=workers) as executor:
            future_to_path = {
                executor.submit(process_entry, (str(path), args.dry_run)): path for path in targets
            }
            for future in as_completed(future_to_path):
                result = future.result()
                results.append(result)
                # if result.processed:
                #     LOGGER.info(
                #         "Wrote %s (%d constants)",
                #         result.path.parent / "lake_constants_withcode.json",
                #         result.constants,
                #     )
    skipped = sum(1 for r in results if not r.processed)
    LOGGER.info(
        "Completed. Processed %d file(s), skipped %d.",
        len(results) - skipped,
        skipped,
    )


if __name__ == "__main__":
    main()
