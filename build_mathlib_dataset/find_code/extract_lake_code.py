#!/usr/bin/env python3
"""
Attach Lean source excerpts to lake constants.

Given a Mathlib directory extracted by lake (where every `*.lean` file lives inside a
directory with the same name that also holds `lake_constants.json`), this script reads
each `lake_constants.json`, keeps the entries whose `line` is non-zero, and writes a
companion `lake_constants_withcode.json` that adds:

* `lean4_code`   – the Lean source snippet that best matches the constant,
* `lean4_start`  – the 1-based line number where the snippet starts,
* `lean4_end`    – the 1-based line number where the snippet ends,
* `subcategory`   – a best-effort classification of the Lean declaration keyword,
* `statement` – the declaration header with comments stripped,
* `proof`  – the proof/body part (when the constant represents a proposition).

Heuristics:
* group constants by their reported `line` so that synthetic constants (e.g. ones
  generated by attributes) share the same snippet as their defining declaration,
* extend snippets upward to include contiguous docstrings and attribute lines,
* extend snippets downward until we detect the beginning of the next top-level command,
  respecting indentation and typical Lean keywords,
* split the captured snippet into statement/proof segments around the first top-level occurrence of `:=`,
  using `isProp`/keywords to decide whether to keep the proof fragment.
"""

