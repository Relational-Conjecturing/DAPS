def indent_of(line: str) -> int:
    """Count leading spaces; Lean style uses spaces exclusively."""
    return len(line) - len(line.lstrip(" "))


def is_attribute_line(stripped: str) -> bool:
    if stripped.startswith("@["):
        closing = stripped.find("]")
        if closing != -1:
            remainder = stripped[closing + 1 :].strip()
            if remainder and not remainder.startswith("--"):
                return False
        return True
    return any(stripped.startswith(prefix) for prefix in ATTRIBUTE_PREFIXES)


def is_probable_command_start(stripped: str) -> bool:
    if not stripped:
        return False
    if stripped.startswith("|"):
        return False
    if stripped.startswith("where"):
        return False
    if stripped.startswith("with"):
        return False
    if stripped.startswith(":="):
        return False
    if stripped.startswith("match "):
        return False
    if stripped.startswith("if "):
        return False
    if stripped.startswith("@["):
        return True
    if stripped[0] == "#":
        return True
    tokens = stripped.split()
    idx = 0
    while idx < len(tokens):
        tok = tokens[idx].rstrip(":")
        if tok in QUALIFIER_TOKENS:
            idx += 1
            continue
        first = tok
        break
    else:
        first = ""
    return first in COMMAND_START_KEYWORDS


def clamp_line_index(idx: int, total: int) -> int:
    if total == 0:
        raise ValueError("Lean file is empty")
    return max(0, min(idx, total - 1))


def skip_block_comment(lines: Sequence[str], start: int) -> int:
    """Return index just after the block comment that starts at `start`."""
    depth = 0
    idx = start
    total = len(lines)
    while idx < total:
        line = lines[idx]
        depth += line.count("/-")
        depth -= line.count("-/")
        idx += 1
        if depth <= 0:
            break
    return idx


def find_declaration_line(lines: Sequence[str], idx: int) -> int:
    """Move forward from idx to the first non-comment, non-attribute line."""
    total = len(lines)
    i = idx
    while i < total:
        stripped = lines[i].strip()
        if not stripped:
            i += 1
            continue
        if stripped.startswith("--"):
            i += 1
            continue
        if stripped.startswith("/-"):
            i = skip_block_comment(lines, i)
            continue
        if is_attribute_line(stripped):
            if stripped.startswith("@["):
                closing = stripped.find("]")
                if closing != -1 and stripped[closing + 1 :].strip():
                    return i
            i += 1
            continue
        return i
    return clamp_line_index(idx, total)


def find_snippet_start(lines: Sequence[str], idx: int) -> int:
    """Extend upwards to include docstrings and attributes contiguous with idx."""
    start_idx = idx
    block_balance = 0
    k = idx - 1
    while k >= 0:
        line = lines[k]
        stripped = line.strip()
        open_count = line.count("/-")
        close_count = line.count("-/")
        if block_balance > 0:
            start_idx = k
            block_balance += close_count - open_count
            k -= 1
            continue
        if not stripped:
            break
        if stripped.startswith("--"):
            start_idx = k
            k -= 1
            continue
        if close_count > open_count:
            start_idx = k
            block_balance = close_count - open_count
            k -= 1
            continue
        if open_count > close_count and stripped.startswith("/-"):
            start_idx = k
            break
        if is_attribute_line(stripped):
            start_idx = k
            k -= 1
            continue
        break
    return start_idx


def find_snippet_end(
    lines: Sequence[str],
    decl_idx: int,
    next_line: Optional[int],
) -> int:
    total = len(lines)
    limit_idx = total - 1
    base_indent = indent_of(lines[decl_idx])
    last_substantive = decl_idx
    k = decl_idx + 1
    while k <= limit_idx:
        line = lines[k]
        stripped = line.strip()
        if stripped:
            indent = indent_of(line)
            if indent <= base_indent and k > decl_idx:
                if is_probable_command_start(stripped):
                    break
                if stripped.startswith("/-") or stripped.startswith("--"):
                    break
            if (
                next_line is not None
                and k >= next_line - 1
                and indent <= base_indent
                and (stripped.startswith("/-") or stripped.startswith("--"))
            ):
                break
            last_substantive = k
        k += 1
    return last_substantive


def find_top_level_assignment(
    raw_lines: Sequence[str],
    start_offset: int,
) -> Tuple[Optional[int], Optional[int]]:
    stack: List[str] = []
    in_block_comment = False
    in_string = False
    current_quote = ""
    escape = False
    for rel_idx in range(start_offset, len(raw_lines)):
        line = raw_lines[rel_idx]
        i = 0
        length = len(line)
        while i < length:
            ch = line[i]
            nxt = line[i + 1] if i + 1 < length else ""
            if not in_string and not in_block_comment and ch == "-" and nxt == "-":
                break
            if not in_string and ch == "/" and nxt == "-":
                in_block_comment = True
                i += 2
                continue
            if in_block_comment:
                if ch == "-" and nxt == "/":
                    in_block_comment = False
                    i += 2
                else:
                    i += 1
                continue
            if ch in {"\"", "'"}:
                if not in_string:
                    in_string = True
                    current_quote = ch
                    escape = False
                elif ch == current_quote and not escape:
                    in_string = False
                    current_quote = ""
                escape = ch == "\\" and not escape
                i += 1
                continue
            escape = ch == "\\" and in_string
            if in_string:
                i += 1
                continue
            closer = BRACKET_PAIRS.get(ch)
            if closer:
                stack.append(closer)
                i += 1
                continue
            if stack and ch == stack[-1]:
                stack.pop()
                i += 1
                continue
            if ch == ":" and nxt == "=" and not stack:
                return rel_idx, i
            i += 1
    return None, None


def extract_snippet(
    lines: Sequence[str],
    line_no: int,
    next_line: Optional[int],
) -> Snippet:
    idx = clamp_line_index(line_no - 1, len(lines))
    decl_idx = find_declaration_line(lines, idx)
    start_idx = find_snippet_start(lines, idx)
    start_idx = min(start_idx, decl_idx)
    end_idx = find_snippet_end(lines, decl_idx, next_line)
    end_idx = max(end_idx, decl_idx)
    enclosing = find_enclosing_structure_line(lines, decl_idx)
    if enclosing is not None:
        parent_start_idx, parent_decl_idx = enclosing
        if parent_start_idx < start_idx:
            parent_end_idx = find_snippet_end(lines, parent_decl_idx, next_line)
            start_idx = parent_start_idx
            end_idx = max(end_idx, parent_end_idx)
    code = "".join(lines[start_idx : end_idx + 1])
    return Snippet(start_idx, end_idx, decl_idx, code)


def read_lines(path: Path) -> List[str]:
    return path.read_text(encoding="utf-8").splitlines(keepends=True)


def load_constants(path: Path) -> List[dict]:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def select_lean_file(dir_path: Path) -> Optional[Path]:
    lean_files = sorted(p for p in dir_path.glob("*.lean") if p.is_file())
    if not lean_files:
        return None
    direct_match = dir_path.name
    for path in lean_files:
        if path.name == direct_match:
            return path
    return lean_files[0]


